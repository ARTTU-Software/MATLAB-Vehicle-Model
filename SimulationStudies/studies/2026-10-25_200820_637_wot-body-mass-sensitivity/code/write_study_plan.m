function write_study_plan(studyFolder,cfg,stamp)
%write_study_plan Write the concrete WOT plan and approval boundaries.
%   write_study_plan(STUDYFOLDER,CFG,STAMP) writes study_plan.md using
%   the prepared configuration and local preparation timestamp. It
%   neither simulates nor changes any original project/model data.
%   Example: write_study_plan(studyFolder,cfg,stamp);
fid = fopen(fullfile(studyFolder,'study_plan.md'),'w');
assert(fid>=0,'Study:Plan','Cannot write the plan.');
cleanup = onCleanup(@() fclose(fid));
fprintf(fid,'# WOT body-mass sensitivity\n\nPrepared %s (Europe/Bucharest), %s.\n',stamp,computer);
fprintf(fid,['\n## Confirmed scope\nSequential macOS execution from isolated saved-file baselines.\n' ...
    'Default controller; temporarily comment through `sm_car/Controller/Default/State Estimation`.\n' ...
    'Change only body mass; preserve body CG and inertia. Nominal saved body mass: %.2f kg.\n' ...
    'User confirmed: 100%% throttle phase, then native braking from 7 s.\n' ...
    'No full-run time limit: StopTime=Inf; actual model stop determines completion.\n'],cfg.nominalBodyMass_kg);
fprintf(fid,'\n## Expanded full cases\n| ID | Body mass (kg) | Offset (kg) | Controller |\n| --- | --- | --- | --- |\n');
for k = 1:height(cfg.runs)
    fprintf(fid,'| %s | %.2f | %+g | %s |\n',cfg.runs.ID(k), ...
        cfg.runs.BodyMass_kg(k),cfg.runs.BodyMassOffset_kg(k),cfg.runs.Controller(k));
end
fprintf(fid,['\n## Maneuver and temporary changes\n' ...
    'Run the complete saved hyperlink in order: set tire class to MFEval, then\n' ...
    '`sm_car_config_maneuver(''sm_car'',''WOT Braking'')`.\n' ...
    'Change selected Maneuver.Accel.rPedal.Value to [0,0,1,1,0,0].\n' ...
    'Throttle times [0,1,1.2,6,6.2,200] s; zero steering.\n' ...
    'Keep brake times [0,7,7.2,190,191,200] s and pedal [0,0,0.7,0.7,0,0].\n' ...
    'Set Vehicle.Chassis.Body.m.Value after baseline and maneuver setup.\n' ...
    'Also override the physical body mask chassis_mass explicitly for the run.\n' ...
    'This avoids relying on parent mask workspace refresh during InitFcn.\n' ...
    'Mass source: sm_car_ARTTU_Chassis.xlsx / Body / C14; never edit workbook.\n' ...
    'Verify effective mass through physical body mask chassis_mass, controller/active label,\n' ...
    'Commented=through, unchanged sCG/J and exact pedal data after initialization.\n' ...
    'Native low-speed stop: below 0.1 m/s after 5 s, expected after braking.\n' ...
    'Other model stops remain active. Any ModelStop is completed at its actual time.\n' ...
    'Label roll/lateral-deviation causes only from actual logged gated requests.\n' ...
    'Errors, interruptions, timeouts and pauses are incomplete; fail fast with no automatic retry.\n']);
fprintf(fid,['\n## Outputs and preview layout\n' ...
    'VehBus.Values.Chassis.Body.CG.vx: m/s to km/h; gx: m/s^2.\n' ...
    'Two light-mode PNG overlays, native timestamps, one trace per mass.\n' ...
    'Signed-G metric CSV and PNG table: mass, offset, positive maximum, most negative minimum,\n' ...
    'peak times, actual stop time and recorded interval; g = gx/9.80665.\n' ...
    'Use all valid recorded samples, without filtering or resampling; NaN for an absent sign.\n' ...
    'Expose unequal run windows; no ranking or narrative report. Save only these two signal leaves\n' ...
    'and compact execution/input metadata in MAT files.\n' ...
    'Previews load the shared Skidpad archive directly in memory, repeat actual traces for layout,\n' ...
    'and explicitly say PREVIEW ONLY - historical Skidpad data, not WOT results.\n' ...
    'Remove only the four study-owned previews after successful verified real exports.\n']);
fprintf(fid,['\n## Validation and approval gates\n' ...
    'Short validation: one additional %.1f s run, R003 (265.07 kg, +10 kg).\n' ...
    'All masses share one compiled model configuration; scalar mass changes need no separate validation.\n' ...
    'This extends 0.1 s beyond the full-throttle ramp and checks the representative effective mass,\n' ...
    'the bypass, stopping parameters, profiles and requested signal extraction.\n' ...
    'It does not validate the later throttle release, braking dynamics or natural stop.\n' ...
    'Review these previews/plan and obtain explicit validation approval first.\n' ...
    'Present validation findings, then obtain separate full execution approval.\n' ...
    'Approval records are retained in state.mat at stage execution; none carried from older studies.\n' ...
    'Full execution has no time limit or runtime guarantee.\n' ...
    'Known historical MFEval low-speed/load/coefficient warnings may recur.\n' ...
    'Successful execution does not by itself establish tire-model validity.\n'],cfg.validationSeconds);
fprintf(fid,['\n## Baseline and retention\nCurrent saved files, including saved local changes, are the baseline.\n' ...
    'Preserve the live MATLAB session and unsaved work; stages use separate batch processes.\n' ...
    'Shared inventory: ../../inventory/saved; mappings: ../../MODEL_WORKSPACE.md.\n' ...
    'Prior 2026-10-25_195833_409 attempt stopped in InitFcn: workspace mass 265.07 kg,\n' ...
    'body-mask resolution 255.07 kg. No simulation interval completed. Its failed log and\n' ...
    'input readback remain in that study. This fresh attempt uses an explicit physical mass override.\n' ...
    'Keep baseline.zip, hashes, local code/JSON/wrapper, compact state and selected results.\n' ...
    'Remove temporary project copies; retain failed-stage transcripts only.\n' ...
    'Clean validation data after successful full exports.\n']);
end
